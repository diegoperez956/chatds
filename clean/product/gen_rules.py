"""Compile condition-14 rule regexes to bounded Thompson NFAs (no libc regex).
Generated tables contain rules, never dev-case outputs. Regenerate after rules changes.
"""
import json
import os
import pathlib
import sys
# rules builds one alternation from a set; pin generation order, not semantics.
if os.environ.get('PYTHONHASHSEED') != '0':
    os.execve(sys.executable, [sys.executable, __file__, *sys.argv[1:]], dict(os.environ, PYTHONHASHSEED='0'))
from re import _parser as sp, _constants as sc
ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / 'campaign/router'), str(ROOT / 'corpus/kb'), str(ROOT / 'corpus')]
import rules
import retrieve4 as r4
patterns = {('act_' + a).upper(): '^' + rx + '$' for a, rx in rules.ACT.items()}
patterns.update(UNSUP=rules.UNSUP, SHELL=rules.SHELL, PYTHON=rules.PYTHON, TEXT=rules.TEXT,
                CALC=rules.CALC, CLARIFY=rules.CLARIFY, FACT_CUE=rules.FACT_CUE,
                AMBIG='^(?:what is|whats|tell me about|who is|define) (?:a |the )?(' + '|'.join(sorted(rules.AMBIG)) + ')$',
                MASH=r'^(?:[a-z]*(?:asdf|qwer|zxcv|sdfg|dfgh|fghj|ghjk|hjkl|wert|erty|rtyu|tyui|yuio|uiop|xcvb|cvbn|vbnm)[a-z]*|[b-df-hj-np-tv-z]{5,})$',
                FILE=r'\b\w+\.[a-z]{1,4}\b', PRON=r'\b(he|she|him|her|his|hers)\b',
                MULTI=r'\b(and|then|also)\b', PY_META=r'\b(what is|whats|explain|why|how does|how do i|what does)\b.*\bpython\b',
                PY_TERMS=r'\b(list|function|loop|dictionary|exception|error|decorator|class|comprehension|tuple|range)\b|\d',
                SURNAME=r'\b(last|first) name\b|\bsurname\b', BASH=r'\b(bash|shell)\b',
                PY_SYNTAX=r'\b(python|def|import|lambda)\b|[\[\](){}=_]',
                CALC_FACT=r'\b(population|born|died|year|years|who|capital)\b',
                LIST=r'\b(list|items?|elements?)\b', DIGIT=r'\d', ARITH=r'\d\s*[-+*/%^]|[-+*/%^]\s*\d')
classes, nodes, starts, sizes = [], [], [], []
def cls(bits):
    bits = tuple(bits)
    if bits not in classes: classes.append(bits)
    return classes.index(bits)
def charclass(items):
    chars = set()
    negate = False
    for op, arg in items:
        if op == sc.NEGATE: negate = True
        elif op == sc.LITERAL: chars.add(arg)
        elif op == sc.RANGE: chars.update(range(arg[0], arg[1] + 1))
        elif op == sc.CATEGORY:
            chars.update(c for c in range(128) if (chr(c).isdigit() if arg == sc.CATEGORY_DIGIT else
                chr(c).isspace() if arg == sc.CATEGORY_SPACE else chr(c).isalnum() or c == 95))
        else: raise ValueError((op, arg))
    if negate: chars = set(range(128)) - chars
    return cls([sum(1 << (c % 8) for c in chars if c // 8 == i) for i in range(16)])
# 0 match, 1 char, 2 split, 3 beginning, 4 end, 5 word boundary
for name, pattern in patterns.items():
    base = len(nodes)
    def emit(op, a=0, b=0, arg=0):
        nodes.append([a, b, arg, op]); return len(nodes) - 1 - base
    end = emit(0)
    def seq(items, dest):
        for op, arg in reversed(list(items)):
            if op == sc.LITERAL: dest = emit(1, dest, arg=charclass([(sc.LITERAL, arg)]))
            elif op == sc.NOT_LITERAL: dest = emit(1, dest, arg=charclass([(sc.NEGATE, None), (sc.LITERAL, arg)]))
            elif op == sc.IN: dest = emit(1, dest, arg=charclass(arg))
            elif op == sc.ANY: dest = emit(1, dest, arg=charclass([(sc.NEGATE, None), (sc.LITERAL, 10)]))
            elif op == sc.SUBPATTERN: dest = seq(arg[3], dest)
            elif op == sc.BRANCH:
                alts = [seq(a, dest) for a in arg[1]]
                dest = alts[-1]
                for a in reversed(alts[:-1]): dest = emit(2, a, dest)
            elif op in (sc.MAX_REPEAT, sc.MIN_REPEAT):
                lo, hi, sub = arg
                if hi == sc.MAXREPEAT:
                    split = emit(2, b=dest)
                    nodes[base + split][0] = seq(sub, split)
                    dest = split
                else:
                    for _ in range(hi - lo): dest = emit(2, seq(sub, dest), dest)
                for _ in range(lo): dest = seq(sub, dest)
            elif op == sc.AT:
                dest = emit({sc.AT_BEGINNING: 3, sc.AT_END: 4, sc.AT_BOUNDARY: 5}[arg], dest)
            else: raise ValueError((name, op, arg))
        return dest
    starts.append(seq(sp.parse(pattern), end)); sizes.append(len(nodes) - base)
lines = ['/* SPDX-License-Identifier: MIT; generated by gen_rules.py. */',
         'enum { ' + ', '.join('RX_' + n for n in patterns) + ', RX_COUNT };',
         '#define RX_MAX ' + str(max(sizes)),
         'static const unsigned char rx_class[][16] = {']
lines += ['{' + ','.join(map(str, c)) + '},' for c in classes]
lines += ['};', 'static const rx_node rx_nodes[] = {']
assert max(sizes) < 8192
lines += ['{%d,%d},' % (a | (op << 13), arg if op == 1 else b) for a, b, arg, op in nodes]
lines += ['};', 'static const rx_prog rx_programs[] = {']
offset = 0
for start, size in zip(starts, sizes):
    lines.append('{%d,%d,%d},' % (offset, start, size)); offset += size
lines += ['};']
for name, value in [('AMBIG', rules.AMBIG), ('NUM', rules.NUM_WORDS), ('MATH', rules.MATH_WORDS),
                    ('ENT_STOP', r4.ENT_STOP), ('CONVERSATION', r4.CONVERSATION), ('CUES', r4.CUES),
                    ('GATE_REL', r4.GATE_REL), ('FILL', r4.FILL)]:
    lines.append('static const char R_' + name + '[] = ' + json.dumps(' '.join(sorted(value))) + ';')
out = pathlib.Path(__file__).with_name('rules_tab.h')
text = '\n'.join(lines) + '\n'
if '--check' in sys.argv:
    assert out.read_text() == text, 'stale rules_tab.h'
else: out.write_text(text)
print(len(nodes), 'NFA nodes;', max(sizes), 'maximum active states')
